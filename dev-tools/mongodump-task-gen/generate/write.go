package generate

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"

	"github.com/goccy/go-yaml"
)

// configPath is the checked-in Evergreen config file this generator writes. It is relative to the
// repository root, from which the generator is run.
const configPath = "evergreen/config/mongodump-passthrough.yml"

// WriteConfig regenerates the passthrough Evergreen config and writes it to configPath. Run it from
// the repository root.
func (gen *Generator) WriteConfig() error {
	y, err := gen.marshalYAML()
	if err != nil {
		return err
	}

	if err := os.WriteFile(configPath, y, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", configPath, err)
	}

	return tidyWithPrecious(configPath)
}

func (gen *Generator) marshalYAML() ([]byte, error) {
	const headComment = " This file was generated by running `go run ./dev-tools/mongodump-task-gen`." +
		" Do not edit this file directly!"

	cfg := gen.Configuration()

	var b bytes.Buffer

	enc := yaml.NewEncoder(
		&b,
		yaml.UseLiteralStyleIfMultiline(true),
		yaml.WithComment(yaml.CommentMap{
			"$.buildvariants": []*yaml.Comment{yaml.HeadComment(headComment)},
		}),
	)

	// Encode a map rather than the Configuration struct so that the keys are emitted in a stable,
	// alphabetical order (buildvariants before tasks), which puts the generated-file comment at the
	// top of the file.
	toEncode := map[string]any{
		"buildvariants": cfg.Variants,
		"tasks":         cfg.Tasks,
	}

	if err := enc.Encode(toEncode); err != nil {
		return nil, fmt.Errorf("marshaling config to YAML: %w", err)
	}

	return b.Bytes(), nil
}

// tidyWithPrecious formats the generated file so that it matches the formatting used by the rest of
// the repo's YAML. Without this the up-to-date check would never be stable.
func tidyWithPrecious(path string) error {
	cmd := exec.Command(
		"mise", "exec", "github:houseabsolute/precious", "--", "precious", "tidy", path,
	)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	if err := cmd.Run(); err != nil {
		return fmt.Errorf("running precious tidy on %s: %w", path, err)
	}

	return nil
}
